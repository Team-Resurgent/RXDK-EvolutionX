# Map EvoX's own functions (0x11000..0x26A80 and the _text/text sections): size, callers, callees
# and the strings each one uses, from the Ghidra export in rea/decomp and the original's code.
# usage: python tools/funcmap.py > docs/functions.md
import capstone, os, re, struct, collections

root = os.path.join(os.path.dirname(__file__), '..')
d = open(os.path.join(root, 'work', 'evoxdash_unpacked.xbe'), 'rb').read()
BASE = 0x10000
nsec, secha = struct.unpack_from('<II', d, 0x11C)
secs = []
for i in range(nsec):
    fl, va, vs, ra, rs, na = struct.unpack_from('<IIIIII', d, secha - BASE + i * 56)
    secs.append((va, vs, ra, rs))

def raw(va):
    for v, vs, r, rs in secs:
        if v <= va < v + rs:
            return r + va - v
    return None

strs = {}
for va, vs, r, rs in secs[6:8]:  # .rdata, .data
    for m in re.finditer(rb'[ -~\t\r\n]{4,}\0', d[r:r + rs]):
        strs[va + m.start()] = m.group()[:-1].decode().strip()

APP = [(0x11000, 0x26A81), (0x5958A0, 0x59641D), (0x596420, 0x596919)]
def in_app(a): return any(s <= a < e for s, e in APP)

funcs = {}
fdir = os.path.join(root, 'rea', 'decomp', 'functions')
for f in os.listdir(fdir):
    m = re.match(r'(?:_?text_)?0x([0-9a-f]+)\.c$', f)
    if not m:
        continue
    a = int(m.group(1), 16)
    if not in_app(a):
        continue
    t = open(os.path.join(fdir, f), encoding='latin-1').read()
    rs = [(int(x, 16), int(y, 16) + 1) for x, y in re.findall(r'^// range: (0x[0-9a-f]+)-(0x[0-9a-f]+)', t, re.M)]
    funcs[a] = rs

md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
md.skipdata = True
callers = collections.defaultdict(set)
info = {}
for a, rs in funcs.items():
    size, used, calls = 0, [], set()
    for s, e in rs:
        size += e - s
        for i in md.disasm(d[raw(s):raw(s) + (e - s)], s):
            for m in re.finditer(r'0x[0-9a-f]+', i.op_str):
                v = int(m.group(), 16)
                if v in strs and strs[v] not in used:
                    used.append(strs[v])
                if i.mnemonic == 'call' and v in funcs:
                    calls.add(v)
    for c in calls:
        callers[c].add(a)
    info[a] = (size, used, calls)

print('# EvoX functions\n')
print('Generated by `tools/funcmap.py` from the original. Status: rebuilt functions name their source.\n')
print('| Address | Size | Callers | Calls | Strings |')
print('|---|---|---|---|---|')
for a in sorted(info):
    size, used, calls = info[a]
    s = '; '.join(x.replace('|', '/').replace('\n', ' ')[:40] for x in used[:4])
    print('| 0x%X | %d | %d | %d | %s |' % (a, size, len(callers[a]), len(calls), s))
print('\n%d functions, %d bytes' % (len(info), sum(v[0] for v in info.values())))
