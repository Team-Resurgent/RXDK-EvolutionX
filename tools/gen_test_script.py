# Turn a test script into the header src/testscript.cpp includes.
# usage: python tools/gen_test_script.py tests/settings.txt work/test/settings.h
#
# Script lines (# starts a comment):
#   <frame> <command>     at that frame of Run (counted from 1)
#   +<n> <command>        n frames after the previous step
# Commands:
#   action <n>            run dashboard action n (as a menu item would)
#   a b x y black white left_trigger right_trigger      one frame of that button
#   up down left right start back                       one frame of that D-pad / button
#   <button>*<n>          n presses, 12 frames apart (the screens wait 8 frames between moves)
#   type <c>              a typed character (keyboard)
#   log <text>            a line in the log
#   dump <path>           the file's contents in the log
#   menus                 the main, BIOS, skin and trainer menus in the log
#   hash <path>           the file's size and MD5 in the log
#   blocks <path>         the MD5 of each 4 KB block of the file in the log
#   igr                   install the in-game reset now (patches the kernel: sandbox only)
import re, sys

ANALOG = {'a': 0, 'b': 1, 'x': 2, 'y': 3, 'black': 4, 'white': 5, 'left_trigger': 6, 'right_trigger': 7}
DIGITAL = {'up': 0x01, 'down': 0x02, 'left': 0x04, 'right': 0x08, 'start': 0x10, 'back': 0x20}
GAP = 12


def c_string(s):
    return '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


steps, frame = [], 0
for n, line in enumerate(open(sys.argv[1]), 1):
    line = line.split('#', 1)[0].strip()
    if not line:
        continue
    when, cmd = line.split(None, 1)
    frame = frame + int(when[1:]) if when.startswith('+') else int(when)
    word, _, rest = cmd.partition(' ')
    m = re.match(r'(\w+)\*(\d+)$', word)
    name, count = (m.group(1), int(m.group(2))) if m else (word, 1)
    for i in range(count):
        f = frame + i * GAP
        if name in ANALOG:
            steps.append((f, 'B', ANALOG[name], None))
        elif name in DIGITAL:
            steps.append((f, 'D', DIGITAL[name], None))
        elif name == 'action':
            steps.append((f, 'A', int(rest), None))
        elif name == 'type':
            steps.append((f, 'K', ord(rest.strip()[0]), None))
        elif name == 'log':
            steps.append((f, 'L', 0, rest))
        elif name == 'hash':
            steps.append((f, 'H', 0, rest.strip()))
        elif name == 'blocks':
            steps.append((f, 'S', 0, rest.strip()))
        elif name == 'igr':
            steps.append((f, 'I', 0, None))
        elif name == 'menus':
            steps.append((f, 'M', 0, None))
        elif name == 'dump':
            steps.append((f, 'F', 0, rest.strip()))
        else:
            raise SystemExit('%s:%d: unknown command %r' % (sys.argv[1], n, name))
    frame += (count - 1) * GAP

with open(sys.argv[2], 'w', newline='\n') as out:
    out.write('// generated by tools/gen_test_script.py from %s\n' % sys.argv[1])
    out.write('static const TestStep g_TestScript[] = {\n')
    for f, op, arg, text in steps:
        out.write("    {%d, '%s', %d, %s},\n" % (f, op, arg, c_string(text) if text else 'nullptr'))
    out.write('};\n')
print('%s: %d steps, last at frame %d' % (sys.argv[2], len(steps), frame))
