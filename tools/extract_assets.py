# Extract the graphics EvoX carries inside its XBE from the user's own evoxdash.xbe (build 3935),
# and write an assembler file that links them into the rebuild. Nothing extracted is committed.
# usage: python tools/extract_assets.py evoxdash.xbe <outdir>   -> <outdir>/*.bin, <outdir>/assets.S
#        python tools/extract_assets.py --none <outdir>         -> assets.S with empty assets
import os, struct, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from unpack_evox import unpack

DATA_VA, DATA_RAW = 0x836E0, 0x75000  # .data of the unpacked image (raw offset = file offset)

# (symbol, address, size, magic, what)
ASSETS = [
    ('g_FontXpr', 0x83750, 0x11000, b'XPR0', 'XPR with the font texture and glyphs (CXBFont)'),
    ('g_ResourceXpr', 0xCF240, 0x26E000, b'XPR0', 'XPR with 4 resources (CXBPackedResource)'),
    ('g_LogoMesh', 0x33D240, 0x96F00, b'XBG\x02', 'XBG mesh (CXBMesh)'),
]


def write_asm(path, files):
    # .data: the loaders may fix up resource headers in place. Page-aligned, which keeps the
    # alignment the original had (16 bytes or more) for the video-memory parts.
    lines = ['# generated by tools/extract_assets.py', '.data']
    for sym, addr, size, magic, what in ASSETS:
        lines += ['', '# %s, 0x%X in the original: %s' % (sym, addr, what), '.balign 4096',
                  '.globl _%s' % sym, '_%s:' % sym]
        if files:
            lines.append('.incbin "%s"' % files[sym].replace('\\', '/'))
        lines += ['.balign 4', '.globl _%sSize' % sym, '_%sSize:' % sym, '.long %s' % (size if files else 0)]
    open(path, 'w', newline='\n').write('\n'.join(lines) + '\n')


def main():
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    if sys.argv[1] == '--none':
        write_asm(os.path.join(out, 'assets.S'), None)
        return
    image = unpack(open(sys.argv[1], 'rb').read())
    files = {}
    for sym, addr, size, magic, what in ASSETS:
        o = addr - DATA_VA + DATA_RAW
        blob = image[o:o + size]
        if blob[:len(magic)] != magic:
            raise SystemExit('%s: no %r at 0x%X' % (sym, magic, addr))
        if magic == b'XPR0' and struct.unpack_from('<I', blob, 4)[0] != size:
            raise SystemExit('%s: XPR size mismatch' % sym)
        if magic.startswith(b'XBG'):
            _, _, sys_size, vid_size = struct.unpack_from('<4I', blob)
            if 16 + sys_size + vid_size != size:
                raise SystemExit('%s: XBG size mismatch' % sym)
        files[sym] = os.path.join(out, sym + '.bin')
        open(files[sym], 'wb').write(blob)
    write_asm(os.path.join(out, 'assets.S'), files)
    print('extracted %d assets to %s' % (len(files), out))


if __name__ == '__main__':
    main()
